# Parsing
# --------------------------------------------------------------------------


def parse_pattern_file(lang: str) -> dict:
    """Decode one hyph_*.dic exactly like pyphen and return its pattern lines.

    The first line declares the encoding.  Every following line is stripped;
    empty lines, ``%``/``#`` comments and the four *HYPHENMIN directives are
    dropped (pyphen does the same; those lines are not patterns).  The
    remaining text is kept verbatim, including ``^^hh`` escapes and ``/alt=``
    forms, because the MoonBit parser interprets them at runtime.
    """
    rel_path = "vendor/upstream/pyphen/hyph_%s.dic" % lang
    raw = read_bytes(rel_path)
    header, sep, remainder = raw.partition(b"\n")
    if not sep:
        raise GenError("%s: missing encoding header line" % rel_path)
    encoding = header.decode("ascii").strip()
    if encoding.lower() == "microsoft-cp1251":
        encoding = "cp1251"
    decoded = remainder.decode(encoding)
    lines: list[str] = []
    for line in decoded.split("\n"):
        line = line.strip()
        if not line or line.startswith(PYPHEN_IGNORED):
            continue
        lines.append(line)
    return {
        "path": rel_path,
        "encoding": encoding,
        "bytes": len(raw),
        "sha256": sha256_hex(raw),
        "lines": lines,
    }


def norm_patterns(hd) -> dict:
    """Normalize a parsed HyphDict for equality checks (keeps /alt= payloads)."""
    out = {}
    for key, (start, values) in hd.patterns.items():
        out[key] = (
            start,
            tuple((int(v), getattr(v, "data", None)) for v in values),
        )
    return out


def verify_patterns_roundtrip(lang: str, lines: list[str]) -> pyphen.Pyphen:
    """Prove that re-encoding the decoded lines to UTF-8 is behavior-preserving.

    The temporary ``.dic`` lives in the OS temp directory (``tempfile``) and
    is removed on exit: the repository itself is never written by ``--check``.

    Returns the pyphen instance parsed from the re-encoded (generated) lines so
    callers can compute fallbacks from the generated tables, not the source.
    """
    source_path = REPO / ("vendor/upstream/pyphen/hyph_%s.dic" % lang)
    with tempfile.TemporaryDirectory(prefix="moon_textstat_l2_") as tmp:
        tmp_path = Path(tmp) / ("hyph_%s.dic" % lang)
        payload = "UTF-8\n" + "\n".join(lines) + "\n"
        tmp_path.write_bytes(payload.encode("utf-8"))
        original = pyphen.Pyphen(filename=str(source_path))
        regenerated = pyphen.Pyphen(filename=str(tmp_path))
    if norm_patterns(original.hd) != norm_patterns(regenerated.hd):
        raise GenError("%s: re-encoded lines change pyphen patterns" % lang)
    if original.hd.maxlen != regenerated.hd.maxlen:
        raise GenError("%s: re-encoded lines change pyphen maxlen" % lang)
    return regenerated


def parse_cmudict() -> tuple[dict[str, list[str]], list[str]]:
    """Parse cmudict exactly like ``nltk.corpus.cmudict.dict()``.

    Per line ``WORD COUNTER PHONES...`` -- key is ``WORD.lower()``, value is the
    phone list starting at index 2, and a word's first pronunciation is the
    first line for that word in file order.
    """
    first: dict[str, list[str]] = {}
    order: list[str] = []
    with open(REPO / CMUDICT_REL, encoding="utf-8") as stream:
        for line in stream:
            pieces = line.split()
            if not pieces:
                continue
            word = pieces[0].lower()
            if word not in first:
                first[word] = pieces[2:]
                order.append(word)
    return first, order


def cmu_syllables(phones: list[str]) -> int:
    return sum(1 for phone in phones if phone[-1].isdigit())


def load_easy_words(root: str) -> list[str]:
    rel_path = "vendor/upstream/easy_words/%s/easy_words.txt" % root
    text = read_bytes(rel_path).decode("utf-8")
    words = set()
    for line in text.split("\n"):
        line = line.strip()
        if line:
            words.add(line)
    return sorted(words)


