def validate_source(content: str, label: str) -> dict:
    if content.count(MARKER) != 1:
        raise GenError(
            "%s: expected exactly one generated marker, found %d"
            % (label, content.count(MARKER))
        )
    max_columns = 0
    for line in content.split("\n"):
        if len(line) > max_columns:
            max_columns = len(line)
    if max_columns >= MAX_LINE_COLUMNS:
        raise GenError(
            "%s: longest line is %d columns (limit < %d)"
            % (label, max_columns, MAX_LINE_COLUMNS)
        )
    forbidden = FORBIDDEN_RE.search(content)
    if forbidden is not None:
        raise GenError(
            "%s: source contains forbidden token %r at offset %d"
            % (label, forbidden.group(0), forbidden.start())
        )
    return {"max_line_columns": max_columns}


def build_outputs(data: GeneratedData) -> dict[str, tuple[str, dict]]:
    outputs: dict[str, tuple[str, dict]] = {}
    content, info = render_pronunciation(data)
    outputs["lib/data/pronunciation_data.mbt"] = (content, info)
    content, info = render_patterns(data)
    outputs["lib/data/hyphenation_patterns_data.mbt"] = (content, info)
    content, info = render_easy_words(data)
    outputs["lib/data/easy_words_data.mbt"] = (content, info)
    return outputs


def make_manifest(data: GeneratedData, outputs: dict[str, tuple[str, dict]]) -> str:
    sources = {}
    for lang in PATTERN_LANGS:
        info = data.patterns[lang]
        sources["pyphen/hyph_%s" % lang] = {
            "path": info["path"],
            "bytes": info["bytes"],
            "sha256": info["sha256"],
            "declared_encoding": info["encoding"],
            "pattern_lines": len(info["lines"]),
            "distinct_patterns": info["distinct_patterns"],
            "pinned_pattern_lines": info["pinned_lines"],
        }
    cmu_raw = read_bytes(CMUDICT_REL)
    sources["cmudict"] = {
        "path": CMUDICT_REL,
        "bytes": len(cmu_raw),
        "sha256": sha256_hex(cmu_raw),
    }
    for root in EASY_ROOTS:
        rel_path = "vendor/upstream/easy_words/%s/easy_words.txt" % root
        raw = read_bytes(rel_path)
        sources["easy_words/%s" % root] = {
            "path": rel_path,
            "bytes": len(raw),
            "sha256": sha256_hex(raw),
            "entries": len(data.easy_words[root]),
            "pinned_entries": PINNED_EASY_ENTRIES[root],
        }

    output_entries = {}
    for rel_path in sorted(outputs):
        content, info = outputs[rel_path]
        raw = content.encode("utf-8")
        entry = {
            "bytes": len(raw),
            "sha256": sha256_hex(raw),
            "payload_chars": info["payload_chars"],
            "chunks": info["chunks"],
            "source_lines": content.count("\n"),
            "max_line_columns": validate_source(content, rel_path)["max_line_columns"],
        }
        output_entries[rel_path] = entry

    manifest = {
        "schema": 1,
        "generator": "tools/gen_data.py",
        "marker": MARKER,
        "chunk_chars": CHUNK_CHARS,
        "guard_tokens": list(GUARD_TOKENS),
        "pinned": {
            "pronunciation_entries": PINNED_PRONUNCIATION_ENTRIES,
            "pronunciation_unsorted_tsv_bytes": PINNED_PRONUNCIATION_TSV_BYTES,
            "pronunciation_unsorted_tsv_sha256": PINNED_PRONUNCIATION_TSV_SHA256,
            "pattern_lines": PINNED_PATTERN_LINES,
            "easy_word_entries": PINNED_EASY_ENTRIES,
        },
        "pronunciation": {
            "entries": data.pronunciation_entries,
            "sorted": True,
            "unsorted_tsv_bytes": data.pronunciation_tsv_bytes,
            "unsorted_tsv_sha256": data.pronunciation_tsv_sha256,
            "payload_chars": len(data.pronunciation_payload),
        },
        "easy_words": {
            root: {
                "entries": len(data.easy_words[root]),
                "payload_chars": len("\n".join(data.easy_words[root])),
            }
            for root in EASY_ROOTS
        },
        "sources": sources,
        "outputs": output_entries,
        "verification": {
            "l1_files_checked": data.l1_checked,
            "l1_mismatch": len(data.l1_failures),
            "oracle_samples": len(data.sample_rows),
            "oracle_samples_mismatch": sum(1 for row in data.sample_rows if not row[3]),
            "oracle_samples_es": len(data.sample_es_rows),
            "oracle_samples_es_mismatch": sum(
                1 for row in data.sample_es_rows if not row[3]
            ),
        },
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def print_report(data: GeneratedData) -> None:
    print("L1_CHECKED=%d L1_MISMATCH=%d" % (data.l1_checked, len(data.l1_failures)))
    for failure in data.l1_failures:
        print("L1_FAIL %s" % failure)
    pinned_bad = data.pronunciation_entries != PINNED_PRONUNCIATION_ENTRIES
    print(
        "PRONUNCIATION entries=%d pinned=%d %s"
        % (
            data.pronunciation_entries,
            PINNED_PRONUNCIATION_ENTRIES,
            "FAIL" if pinned_bad else "OK",
        )
    )
    for lang in PATTERN_LANGS:
        info = data.patterns[lang]
        pinned = info["pinned_lines"]
        if pinned is None:
            print(
                "PATTERNS %-5s lines=%d pinned=unpinned encoding=%s distinct=%d"
                % (lang, len(info["lines"]), info["encoding"], info["distinct_patterns"])
            )
        else:
            ok = len(info["lines"]) == pinned
            print(
                "PATTERNS %-5s lines=%d pinned=%d %s"
                % (lang, len(info["lines"]), pinned, "OK" if ok else "FAIL")
            )
    for root in EASY_ROOTS:
        count = len(data.easy_words[root])
        pinned = PINNED_EASY_ENTRIES[root]
        print(
            "EASY_WORDS %-2s entries=%d pinned=%d %s"
            % (root, count, pinned, "OK" if count == pinned else "FAIL")
        )
    for sample_id, computed, expected, ok in data.sample_rows:
        print(
            "SAMPLE %-28s computed=%-5d oracle=%-5d %s"
            % (sample_id, computed, expected, "OK" if ok else "MISMATCH")
        )
    print(
        "SAMPLES=%d MISMATCH=%d"
        % (len(data.sample_rows), sum(1 for row in data.sample_rows if not row[3]))
    )
    print(
        "SAMPLES_ES=%d MISMATCH_ES=%d"
        % (
            len(data.sample_es_rows),
            sum(1 for row in data.sample_es_rows if not row[3]),
        )
    )


def write_outputs(outputs: dict[str, tuple[str, dict]], manifest: str) -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    for rel_path in sorted(outputs):
        content, _ = outputs[rel_path]
        (REPO / rel_path).write_bytes(content.encode("utf-8"))
        print("WROTE %s" % rel_path)
    MANIFEST_PATH.write_bytes(manifest.encode("utf-8"))
    print("WROTE tools/l2_manifest.json")


def check_outputs(outputs: dict[str, tuple[str, dict]], manifest: str) -> list[str]:
    problems: list[str] = []
    ok = diff = missing = 0
    for rel_path in sorted(outputs):
        expected, _ = outputs[rel_path]
        target = REPO / rel_path
        if not target.exists():
            print("FILE %-44s MISSING" % rel_path)
            problems.append("missing %s" % rel_path)
            missing += 1
            continue
        if target.read_bytes() == expected.encode("utf-8"):
            print("FILE %-44s OK" % rel_path)
            ok += 1
        else:
            print("FILE %-44s DIFF" % rel_path)
            problems.append("diff %s" % rel_path)
            diff += 1
    print("FILES=%d OK=%d DIFF=%d MISSING=%d" % (len(outputs), ok, diff, missing))
    if not MANIFEST_PATH.exists():
        print("MANIFEST MISSING")
        problems.append("missing tools/l2_manifest.json")
    elif MANIFEST_PATH.read_bytes() == manifest.encode("utf-8"):
        print("MANIFEST OK")
    else:
        print("MANIFEST DIFF")
        problems.append("diff tools/l2_manifest.json")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated files and data fidelity without writing",
    )
    args = parser.parse_args(argv)

    try:
        data = build()
    except GenError as exc:
        print("GEN_ERROR %s" % exc)
        print("CHECK=FAIL")
        return 1

    if data.failures:
        print_report(data)
        for failure in data.failures:
            print("FAIL %s" % failure)
        print("CHECK=FAIL")
        return 1

    outputs = build_outputs(data)
    for rel_path in sorted(outputs):
        validate_source(outputs[rel_path][0], rel_path)
    manifest = make_manifest(data, outputs)

    print_report(data)

    if args.check:
        problems = check_outputs(outputs, manifest)
        if problems:
            print("CHECK=FAIL")
            return 1
        print("CHECK=PASS")
        return 0

    write_outputs(outputs, manifest)
    print("CHECK=PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
