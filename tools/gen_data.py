class GeneratedData:
    def __init__(self) -> None:
        self.l1_checked = 0
        self.l1_failures: list[str] = []
        self.pronunciation_sorted: list[tuple[str, int]] = []
        self.pronunciation_tsv_bytes = 0
        self.pronunciation_tsv_sha256 = ""
        self.pronunciation_payload = ""
        self.patterns: dict[str, dict] = {}
        self.easy_words: dict[str, list[str]] = {}
        self.sample_rows: list[tuple[str, int, int, bool]] = []
        self.sample_es_rows: list[tuple[str, int, int, bool]] = []
        self.failures: list[str] = []

    @property
    def pronunciation_entries(self) -> int:
        return len(self.pronunciation_sorted)


def build() -> GeneratedData:
    data = GeneratedData()

    data.l1_checked, data.l1_failures = verify_l1()
    if data.l1_failures:
        data.failures.extend(data.l1_failures)
        return data

    # --- pronunciation table (trimmed) ------------------------------------
    cmu_first, cmu_order = parse_cmudict()
    en_us = pyphen.Pyphen(filename=str(VENDOR / "pyphen" / "hyph_en_US.dic"))
    trimmed_unsorted: list[tuple[str, int]] = []
    for word in cmu_order:
        count = cmu_syllables(cmu_first[word])
        fallback = len(en_us.positions(word)) + 1
        if count != fallback:
            trimmed_unsorted.append((word, count))
    tsv = "".join("%s\t%d\n" % (word, count) for word, count in trimmed_unsorted)
    data.pronunciation_tsv_bytes = len(tsv.encode("utf-8"))
    data.pronunciation_tsv_sha256 = sha256_hex(tsv.encode("utf-8"))
    if len(trimmed_unsorted) != PINNED_PRONUNCIATION_ENTRIES:
        data.failures.append(
            "pronunciation entries: got %d, pinned %d"
            % (len(trimmed_unsorted), PINNED_PRONUNCIATION_ENTRIES)
        )
    if data.pronunciation_tsv_bytes != PINNED_PRONUNCIATION_TSV_BYTES:
        data.failures.append(
            "pronunciation unsorted TSV bytes: got %d, pinned %d"
            % (data.pronunciation_tsv_bytes, PINNED_PRONUNCIATION_TSV_BYTES)
        )
    if data.pronunciation_tsv_sha256 != PINNED_PRONUNCIATION_TSV_SHA256:
        data.failures.append(
            "pronunciation unsorted TSV sha256: got %s, pinned %s"
            % (data.pronunciation_tsv_sha256, PINNED_PRONUNCIATION_TSV_SHA256)
        )
    data.pronunciation_sorted = sorted(trimmed_unsorted)
    data.pronunciation_payload = "\n".join(
        "%s\t%d" % (word, count) for word, count in data.pronunciation_sorted
    )
    trimmed_map = dict(data.pronunciation_sorted)

    # --- hyphenation patterns --------------------------------------------
    for lang in PATTERN_LANGS:
        info = parse_pattern_file(lang)
        verify_patterns_roundtrip(lang, info["lines"])
        hd = pyphen.Pyphen(filename=str(REPO / info["path"])).hd
        info["distinct_patterns"] = len(hd.patterns)
        info["pinned_lines"] = PINNED_PATTERN_LINES.get(lang)
        if info["pinned_lines"] is not None and len(info["lines"]) != info["pinned_lines"]:
            data.failures.append(
                "pattern lines %s: got %d, pinned %d"
                % (lang, len(info["lines"]), info["pinned_lines"])
            )
        data.patterns[lang] = info

    # --- easy words -------------------------------------------------------
    for root in EASY_ROOTS:
        words = load_easy_words(root)
        if len(words) != PINNED_EASY_ENTRIES[root]:
            data.failures.append(
                "easy words %s: got %d, pinned %d"
                % (root, len(words), PINNED_EASY_ENTRIES[root])
            )
        data.easy_words[root] = words

    # --- oracle samples ---------------------------------------------------
    data.sample_rows, data.sample_es_rows, sample_failures = verify_samples(
        trimmed_map,
        en_us,
        pyphen.Pyphen(filename=str(VENDOR / "pyphen" / "hyph_es.dic")),
    )
    data.failures.extend(sample_failures)
    return data


# --------------------------------------------------------------------------
# MoonBit source emission
# --------------------------------------------------------------------------


def guard_offsets(text: str) -> set[int]:
    """Character offsets that must be emitted as ``\\u{..}`` escapes."""
    starts: set[int] = set()
    for token in GUARD_TOKENS:
        offset = text.find(token)
        while offset != -1:
            starts.add(offset)
            offset = text.find(token, offset + 1)
    return starts


def moon_escape(text: str, guarded: set[int] | None = None) -> str:
    guarded = guarded or set()
    out: list[str] = []
    for index, ch in enumerate(text):
        code = ord(ch)
        if index in guarded:
            out.append("\\u{%X}" % code)
        elif ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif code < 0x20 or code == 0x7F:
            out.append("\\u{%X}" % code)
        else:
            out.append(ch)
    return "".join(out)


def chunk_text(text: str, limit: int = CHUNK_CHARS) -> list[str]:
    """Split text into chunks of at most ``limit`` characters.

    Boundaries prefer newlines so a chunk holds whole data lines; a chunk
    ending at a newline keeps that newline, therefore ``"".join(chunks)``
    reproduces ``text`` byte-for-byte.
    """
    chunks: list[str] = []
    start = 0
    length = len(text)
    while start < length:
        end = min(start + limit, length)
        if end < length:
            nl = text.rfind("\n", start, end)
            if nl != -1 and nl + 1 > start:
                end = nl + 1
        chunks.append(text[start:end])
        start = end
    return chunks


def render_array_block(var_name: str, payload: str) -> tuple[str, dict]:
    """Render one ``let <var> : Array[String] = [...]`` block."""
    chunks = chunk_text(payload)
    lines = ["///|", "let %s : Array[String] = [" % var_name]
    for chunk in chunks:
        lines.append('  "%s",' % moon_escape(chunk, guard_offsets(chunk)))
    lines.append("]")
    content = "\n".join(lines) + "\n"
    return content, {"payload_chars": len(payload), "chunks": len(chunks)}


def render_file(
    file_header: list[str],
    arrays: list[tuple[str, str, str]],
    trailer: list[str],
) -> tuple[str, dict]:
    """Render a generated source file: marker + header + arrays + trailer code."""
    lines = [MARKER]
    lines.extend(file_header)
    payload_chars = 0
    chunks = 0
    for var_name, payload, comment in arrays:
        block, info = render_array_block(var_name, payload)
        lines.append("")
        lines.append("// %s" % comment)
        lines.append("")
        lines.extend(block.rstrip("\n").split("\n"))
        payload_chars += info["payload_chars"]
        chunks += info["chunks"]
    if trailer:
        lines.append("")
        lines.extend(trailer)
    content = "\n".join(lines) + "\n"
    return content, {"payload_chars": payload_chars, "chunks": chunks}


def render_pronunciation(data: GeneratedData) -> tuple[str, dict]:
    header = [
        "// L2 CMUdict syllable table (trimmed): every key whose CMU syllable",
        "// count differs from the pyphen en_US fallback, sorted by word.",
        "// Source: %s" % CMUDICT_REL,
        "// Entries: %d; payload characters: %d."
        % (data.pronunciation_entries, len(data.pronunciation_payload)),
    ]
    return render_file(
        header,
        [
            (
                "raw_pronunciation",
                data.pronunciation_payload,
                "trimmed pronunciation table",
            )
        ],
        [],
    )


def render_patterns(data: GeneratedData) -> tuple[str, dict]:
    header = [
        "// L2 hyphenation pattern lines, decoded from each file's declared",
        "// encoding and re-encoded as UTF-8. Pattern text (^^hh and /alt= forms",
        "// included) is preserved verbatim; pyphen comment/directive lines are",
        "// not patterns and are not emitted.",
    ]
    for lang in PATTERN_LANGS:
        info = data.patterns[lang]
        header.append(
            "// %-5s %6d lines, encoding %s"
            % (lang, len(info["lines"]), info["encoding"])
        )
    arrays = [
        (
            "raw_patterns_%s" % lang,
            "\n".join(data.patterns[lang]["lines"]),
            "%s hyphenation pattern lines" % lang,
        )
        for lang in PATTERN_LANGS
    ]
    trailer = ["///|", "let pattern_chunk_sources : Array[(String, Array[String])] = ["]
    for lang in PATTERN_LANGS:
        trailer.append('  ("%s", raw_patterns_%s),' % (lang, lang))
    trailer.append("]")
    return render_file(header, arrays, trailer)


def render_easy_words(data: GeneratedData) -> tuple[str, dict]:
    header = [
        "// L2 easy-word lists: upstream files split into lines, each line",
        "// stripped, empty lines dropped, de-duplicated, sorted.",
    ]
    for root in EASY_ROOTS:
        header.append("// %-2s %6d words" % (root, len(data.easy_words[root])))
    arrays = [
        (
            "raw_easy_words_%s" % root,
            "\n".join(data.easy_words[root]),
            "%s easy words, sorted" % root,
        )
        for root in EASY_ROOTS
    ]
    trailer = ["///|", "let easy_word_chunk_sources : Array[(String, Array[String])] = ["]
    for root in EASY_ROOTS:
        trailer.append('  ("%s", raw_easy_words_%s),' % (root, root))
    trailer.append("]")
    return render_file(header, arrays, trailer)


