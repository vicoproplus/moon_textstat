def validate_source(content: str, label: str) -> dict:
    if content.count(MARKER) != 1:
        raise GenError(
            "%s: expected exactly one generated marker, found %d"
            % (label, content.count(MARKER))
        )
    max_columns = 0
    for line in content.split("\n"):
        if len(line) > max_columns:
            max_columns = len(line)
    if max_columns >= MAX_LINE_COLUMNS:
        raise GenError(
            "%s: longest line is %d columns (limit < %d)"
            % (label, max_columns, MAX_LINE_COLUMNS)
        )
    forbidden = FORBIDDEN_RE.search(content)
    if forbidden is not None:
        raise GenError(
            "%s: source contains forbidden token %r at offset %d"
            % (label, forbidden.group(0), forbidden.start())
        )
    return {"max_line_columns": max_columns}


