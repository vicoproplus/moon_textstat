def ad_section(ad_text: str, number: str) -> str:
    """Return the body of the ``## <number>.`` section of the AD document."""
    heading = "## %s." % number
    body: list[str] = []
    found = False
    for line in ad_text.split("\n"):
        if line.startswith("## "):
            if found:
                break
            found = line.startswith(heading)
            continue
        if found:
            body.append(line)
    if not found:
        raise GenError("AD: section %s. is missing" % number)
    return "\n".join(body)


def parse_ad_ext_shapes(ad_text: str) -> list[str]:
    """Parse the 31 ``[EXT]`` shapes from the AD section 5 table.

    The whitelist is read from its authority document, never typed twice: a
    drift in either the table or the oracle must break generation.
    """
    section = ad_section(ad_text, "5")
    rows = [line for line in section.split("\n") if line.startswith("|")]
    if len(rows) < 3:
        raise GenError("AD section 5: the [EXT] table is missing")
    shapes: list[str] = []
    for row in rows[2:]:  # row 0 is the header, row 1 the separator
        columns = [column.strip() for column in row.split("|")]
        if len(columns) < 5:
            raise GenError("AD section 5: malformed table row %r" % row)
        if "个形态" in row:  # the 合计 (total) row carries no shapes
            continue
        shapes.extend(re.findall(r"`([^`]+)`", columns[2]))
    if len(shapes) != PINNED_L3_EXT_SHAPES:
        raise GenError(
            "AD section 5: parsed %d [EXT] shapes, expected %d"
            % (len(shapes), PINNED_L3_EXT_SHAPES)
        )
    if len(set(shapes)) != len(shapes):
        raise GenError("AD section 5: the [EXT] list repeats a shape")
    return sorted(shapes)


def parse_ad_align_shapes(ad_text: str) -> list[str]:
    """Parse the 24 ``[ALIGN]`` shapes listed in AD section 5."""
    section = ad_section(ad_text, "5")
    needle = "`[ALIGN]` \u7684 **24** \u4e2a\u5f62\u6001\uff1a"
    for line in section.split("\n"):
        if needle in line:
            shapes = re.findall(r"`([^`]+)`", line.split(needle, 1)[1])
            if len(shapes) != PINNED_L3_ALIGN_SHAPES:
                raise GenError(
                    "AD section 5: parsed %d [ALIGN] shapes, expected %d"
                    % (len(shapes), PINNED_L3_ALIGN_SHAPES)
                )
            return sorted(shapes)
    raise GenError("AD section 5: the [ALIGN] shape list is missing")


def parse_ad_probe_fields(ad_text: str) -> tuple[list[str], list[str]]:
    """Parse the six aligned and four excluded language-probe fields."""
    section = ad_section(ad_text, "5")
    needle = "`[ALIGN]` \u5b57\u6bb5\u4e3a **6** \u4e2a\uff1a"
    for line in section.split("\n"):
        if needle in line:
            payload = line.split(needle, 1)[1]
            aligned, separator, excluded = payload.partition("\uff1b")
            if not separator:
                raise GenError("AD section 5: malformed probe-field sentence")
            fields = re.findall(r"`([^`]+)`", aligned)
            excluded_head = excluded.split("\u56db\u4e2a\u5b57\u6bb5")[0]
            rest = re.findall(r"`([^`]+)`", excluded_head)
            if len(fields) != PINNED_L3_PROBE_FIELDS:
                raise GenError(
                    "AD section 5: parsed %d aligned probe fields, expected %d"
                    % (len(fields), PINNED_L3_PROBE_FIELDS)
                )
            if len(rest) != 4:
                raise GenError(
                    "AD section 5: parsed %d excluded probe fields, expected 4"
                    % len(rest)
                )
            return fields, rest
    raise GenError("AD section 5: the probe field sentence is missing")


class L3Cell:
    """One frozen L3 cell; ``kind`` selects the ``Expected`` constructor."""

    __slots__ = (
        "sample_id",
        "shape",
        "lang",
        "group",
        "kind",
        "value",
        "bits",
        "source",
    )

    def __init__(
        self,
        sample_id: str,
        shape: str,
        lang: str,
        group: str,
        kind: str,
        value,
        bits: int,
        source: str,
    ) -> None:
        self.sample_id = sample_id
        self.shape = shape
        self.lang = lang
        self.group = group
        self.kind = kind
        self.value = value
        self.bits = bits
        self.source = source


class L3Data:
    def __init__(self) -> None:
        self.cells: list[L3Cell] = []
        self.align_shapes: list[str] = []
        self.ext_shapes: list[str] = []
        self.probe_fields: list[str] = []
        self.probe_excluded: list[str] = []
        self.probe_codes: list[str] = []
        self.groups: dict[str, int] = {}
        self.sample_cells = 0
        self.lang_cells = 0
        self.pt_cells = 0
        self.ext_cells = 0
        self.oracle_bytes = 0
        self.oracle_sha256 = ""
        self.ad_bytes = 0
        self.ad_sha256 = ""


def l3_group(sample_id: str, shape: str) -> str:
    """Gate group of one sample-side cell (precedence: degenerate first)."""
    if sample_id in DEGENERATE_SAMPLES:
        return "degenerate"
    if shape in VARIANT_SHAPES:
        return "variant"
    if shape in FORMULA_SHAPES:
        return "formula"
    return "count"


def make_l3_cell(
    sample_id: str,
    shape: str,
    lang: str,
    group: str,
    value,
    source: str,
) -> L3Cell:
    """Map one oracle JSON value onto its ``Expected`` kind.

    Bools are rejected: no ``[ALIGN]`` cell is boolean (AD-2 section 2.3), so a
    bool means the oracle drifted. Floats become IEEE-754 bit patterns because
    the printed decimal text is explicitly not the contract (AD-2 section 2.2).
    """
    if isinstance(value, bool):
        raise GenError("L3 cell %s: unexpected JSON bool" % source)
    if isinstance(value, int):
        if value < -(2 ** 31) or value > 2 ** 31 - 1:
            raise GenError(
                "L3 cell %s: integer %d does not fit 32-bit Int" % (source, value)
            )
        return L3Cell(sample_id, shape, lang, group, "int", value, 0, source)
    if isinstance(value, float):
        bits = struct.unpack(">Q", struct.pack(">d", value))[0]
        return L3Cell(sample_id, shape, lang, group, "double", value, bits, source)
    if isinstance(value, list):
        if not all(isinstance(entry, str) for entry in value):
            raise GenError("L3 cell %s: string list holds a non-string" % source)
        return L3Cell(sample_id, shape, lang, group, "list", list(value), 0, source)
    raise GenError(
        "L3 cell %s: unsupported JSON value type %s"
        % (source, type(value).__name__)
    )


def build_l3() -> L3Data:
    """Build the 366 ``[ALIGN]`` cells straight from the frozen oracle."""
    l3 = L3Data()
    ad_raw = read_bytes(AD_REL)
    l3.ad_bytes = len(ad_raw)
    l3.ad_sha256 = sha256_hex(ad_raw)
    ad_text = ad_raw.decode("utf-8").replace("\r\n", "\n")
    l3.ext_shapes = parse_ad_ext_shapes(ad_text)
    l3.align_shapes = parse_ad_align_shapes(ad_text)
    l3.probe_fields, l3.probe_excluded = parse_ad_probe_fields(ad_text)

    oracle_raw = ORACLE_PATH.read_bytes()
    l3.oracle_bytes = len(oracle_raw)
    l3.oracle_sha256 = sha256_hex(oracle_raw)
    doc = json.loads(oracle_raw.decode("utf-8").replace("\r\n", "\n"))
    samples = doc["samples"]
    probes = doc["lang_probes"]
    l3.probe_codes = sorted(probes)

    ext_set = set(l3.ext_shapes)
    align_set = set(l3.align_shapes)
    if len(align_set) != PINNED_L3_ALIGN_SHAPES:
        raise GenError("AD section 5: the [ALIGN] list repeats a shape")
    if align_set & ext_set:
        raise GenError("AD section 5: a shape is listed as both [ALIGN] and [EXT]")

    # --- oracle shape of every sample result set --------------------------
    for sample in samples:
        keys = set(sample["results"])
        if len(keys) != PINNED_RESULTS_KEYS:
            raise GenError(
                "oracle sample %s: %d result keys, expected %d"
                % (sample["id"], len(keys), PINNED_RESULTS_KEYS)
            )
        if not ext_set <= keys:
            raise GenError(
                "oracle sample %s: missing [EXT] keys %s"
                % (sample["id"], sorted(ext_set - keys))
            )
        sample_align = keys - ext_set
        if len(sample_align) != PINNED_L3_ALIGN_SHAPES:
            raise GenError(
                "oracle sample %s: %d [ALIGN] keys, expected %d"
                % (sample["id"], len(sample_align), PINNED_L3_ALIGN_SHAPES)
            )
        if sample_align != align_set:
            raise GenError(
                "oracle sample %s: [ALIGN] keys differ from AD section 5"
                % sample["id"]
            )
        if "results_es" in sample and set(sample["results_es"]) != keys:
            raise GenError(
                "oracle sample %s: results_es keys differ from results"
                % sample["id"]
            )

    # --- oracle shape of every language probe -----------------------------
    if len(l3.probe_codes) != PINNED_PROBES:
        raise GenError(
            "oracle lang_probes: %d codes, expected %d"
            % (len(probes), PINNED_PROBES)
        )
    probe_keys: set[str] = set()
    for code in l3.probe_codes:
        fields = probes[code]
        if len(fields) != PINNED_PROBE_FIELDS_PER_CODE:
            raise GenError(
                "oracle lang_probes.%s: %d fields, expected %d"
                % (code, len(fields), PINNED_PROBE_FIELDS_PER_CODE)
            )
        probe_keys.update(fields)
    declared_probe_keys = set(l3.probe_fields) | set(l3.probe_excluded)
    if probe_keys != declared_probe_keys:
        raise GenError(
            "oracle lang_probes: fields differ from AD section 5 (%s)"
            % sorted(probe_keys ^ declared_probe_keys)
        )

    # --- grouping partition over the 24 [ALIGN] shapes --------------------
    variant = set(VARIANT_SHAPES)
    formula = set(FORMULA_SHAPES)
    if len(variant) != 5 or len(formula) != 8 or variant & formula:
        raise GenError("L3 policy: variant must be 5 shapes and formula 8, disjoint")
    if not (variant | formula) <= align_set:
        raise GenError(
            "L3 policy: shapes outside [ALIGN]: %s"
            % sorted((variant | formula) - align_set)
        )
    count_shapes = align_set - variant - formula
    if len(variant) + len(formula) + len(count_shapes) != PINNED_L3_ALIGN_SHAPES:
        raise GenError("L3 policy: the group partition does not cover 24 shapes")
    if len(count_shapes) != 11:
        raise GenError(
            "L3 policy: the count group has %d shapes, expected 11"
            % len(count_shapes)
        )

    # --- sample-side cells (effective language per result set) ------------
    # Every `results` set was recorded under en_US; only spanish_text's
    # results_es was recorded under es_ES. The sample `lang` field is not used.
    sample_sets = [
        (sample["id"], sample["results"], "en_US", "")
        for sample in samples
    ]
    sample_sets.extend(
        (sample["id"], sample["results_es"], "es_ES", "results_es.")
        for sample in samples
        if "results_es" in sample
    )
    if len(sample_sets) != PINNED_SAMPLE_RESULT_SETS:
        raise GenError(
            "oracle: %d sample result sets, expected %d"
            % (len(sample_sets), PINNED_SAMPLE_RESULT_SETS)
        )
    cells: list[L3Cell] = []
    for sample_id, results, lang, prefix in sample_sets:
        for shape in l3.align_shapes:
            item = results[shape]
            error = item.get("error")
            if error is not None:
                raise GenError(
                    "sample cell %s.%s%s records oracle error %r"
                    % (sample_id, prefix, shape, error)
                )
            source = "%s%s.%s%s" % (L3_SOURCE_PREFIX, sample_id, prefix, shape)
            cells.append(
                make_l3_cell(
                    sample_id,
                    shape,
                    lang,
                    l3_group(sample_id, shape),
                    item.get("value"),
                    source,
                )
            )
    l3.sample_cells = len(cells)

    # --- language-side cells (probe code as sample id and lang) ----------
    for code in l3.probe_codes:
        for field in l3.probe_fields:
            item = probes[code][field]
            source = "%slang_probes.%s.%s" % (L3_SOURCE_PREFIX, code, field)
            error = item.get("error")
            if error is not None:
                if item.get("value") is not None:
                    raise GenError(
                        "language cell %s: oracle records both a value and error"
                        % source
                    )
                cells.append(
                    L3Cell(code, field, code, "errors", "error", str(error), 0, source)
                )
            else:
                cells.append(
                    make_l3_cell(code, field, code, "lang", item.get("value"), source)
                )
    l3.lang_cells = len(cells) - l3.sample_cells

    # --- frozen totals, grouping, and exclusion evidence ------------------
    if l3.sample_cells != PINNED_L3_SAMPLE_CELLS:
        raise GenError(
            "L3: %d sample cells, expected %d"
            % (l3.sample_cells, PINNED_L3_SAMPLE_CELLS)
        )
    if l3.lang_cells != PINNED_L3_LANG_CELLS:
        raise GenError(
            "L3: %d language cells, expected %d"
            % (l3.lang_cells, PINNED_L3_LANG_CELLS)
        )
    if len(cells) != PINNED_L3_CELLS:
        raise GenError("L3: %d cells, expected %d" % (len(cells), PINNED_L3_CELLS))
    groups = {group: 0 for group in L3_GROUP_ORDER}
    for cell in cells:
        if cell.group not in groups:
            raise GenError("L3 cell %s: unknown group %r" % (cell.source, cell.group))
        groups[cell.group] += 1
    if groups != PINNED_L3_GROUPS:
        raise GenError(
            "L3 group breakdown %s differs from pinned %s"
            % (groups, PINNED_L3_GROUPS)
        )
    sources = [cell.source for cell in cells]
    if len(set(sources)) != len(sources):
        raise GenError("L3: duplicate source annotations")

    # [EXT] callables get no expected values (AD section 5).
    l3.ext_cells = sum(1 for cell in cells if cell.shape in ext_set)
    if l3.ext_cells != 0:
        raise GenError("L3: %d cells use an [EXT] shape" % l3.ext_cells)
    # pt is not an acceptance item (A-4.4) and gets no expected values.
    l3.pt_cells = sum(
        1
        for cell in cells
        if cell.lang == "pt"
        or cell.sample_id == "pt"
        or cell.shape.startswith("pt")
        or ".pt." in cell.source
    )
    if l3.pt_cells != 0:
        raise GenError("L3: %d cells are associated with pt" % l3.pt_cells)
    if "pt" in probes or any(sample["id"] == "pt" for sample in samples):
        raise GenError("L3: the oracle carries a pt entry")

    l3.cells = cells
    l3.groups = groups
    return l3


