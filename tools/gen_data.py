def validate_source(content: str, label: str) -> dict:
    if content.count(MARKER) != 1:
        raise GenError(
            "%s: expected exactly one generated marker, found %d"
            % (label, content.count(MARKER))
        )
    max_columns = 0
    for line in content.split("\n"):
        if len(line) > max_columns:
            max_columns = len(line)
    if max_columns >= MAX_LINE_COLUMNS:
        raise GenError(
            "%s: longest line is %d columns (limit < %d)"
            % (label, max_columns, MAX_LINE_COLUMNS)
        )
    forbidden = FORBIDDEN_RE.search(content)
    if forbidden is not None:
        raise GenError(
            "%s: source contains forbidden token %r at offset %d"
            % (label, forbidden.group(0), forbidden.start())
        )
    return {"max_line_columns": max_columns}


def build_outputs(data: GeneratedData) -> dict[str, tuple[str, dict]]:
    outputs: dict[str, tuple[str, dict]] = {}
    content, info = render_pronunciation(data)
    outputs["lib/data/pronunciation_data.mbt"] = (content, info)
    content, info = render_pronunciation_supplement(data)
    outputs["lib/data/pronunciation_supplement_gb_data.mbt"] = (content, info)
    content, info = render_patterns(data)
    outputs["lib/data/hyphenation_patterns_data.mbt"] = (content, info)
    content, info = render_easy_words(data)
    outputs["lib/data/easy_words_data.mbt"] = (content, info)
    content, info = render_l3(data.l3)
    outputs[L3_OUT] = (content, info)
    content, info = render_zh_common_chars(data.zh)
    outputs[ZH_CHARS_OUT] = (content, info)
    content, info = render_zh_cells(data.zh)
    outputs[ZH_CELLS_OUT] = (content, info)
    return outputs


