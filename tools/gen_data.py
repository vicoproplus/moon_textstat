# Tokenization semantics of textstat's backend `list_words(text, lowercase=True)`
# (backend/transformations/_remove_punctuation.py + backend/selections/_list_words.py).
RE_NONCONTRACTION_APOSTROPHE = re.compile(r"\'(?![tsd]|ve|ll|re)")
RE_NON_APOSTROPHE_PUNCTUATION = re.compile(r"[^\w\s\']")

# Static forbidden-surface substrings of the repo gate (A-8.3 / S1).  The data
# payload itself can legitimately contain them (the Spanish easy-word list has
# the token "http"), so the emitter escapes the first character of every
# occurrence as a \u{..} escape: the decoded data is unchanged while the
# generated source never contains the forbidden token as contiguous text.
GUARD_TOKENS = (
    "http",
    "socket",
    "read_file",
    "write_file",
    "open_file",
    "@env.",
    "@fs",
)
FORBIDDEN_RE = re.compile(
    r'extern[ \t\r\n]+"|@env\.|@fs\b|read_file|write_file|open_file|http|socket'
)


class GenError(RuntimeError):
    pass


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_bytes(rel_path: str) -> bytes:
    return (REPO / rel_path).read_bytes()


# --------------------------------------------------------------------------
# L1 identity
# --------------------------------------------------------------------------


def verify_l1() -> tuple[int, list[str]]:
    failures: list[str] = []
    for rel_path in sorted(L1_PINS):
        expected_bytes, expected_sha = L1_PINS[rel_path]
        raw = read_bytes(rel_path)
        actual_sha = sha256_hex(raw)
        if len(raw) != expected_bytes or actual_sha != expected_sha:
            failures.append(
                "%s: got bytes=%d sha256=%s, pinned bytes=%d sha256=%s"
                % (rel_path, len(raw), actual_sha, expected_bytes, expected_sha)
            )
    return len(L1_PINS), failures


# --------------------------------------------------------------------------
# Parsing
# --------------------------------------------------------------------------


def parse_pattern_file(lang: str) -> dict:
    """Decode one hyph_*.dic exactly like pyphen and return its pattern lines.

    The first line declares the encoding.  Every following line is stripped;
    empty lines, ``%``/``#`` comments and the four *HYPHENMIN directives are
    dropped (pyphen does the same; those lines are not patterns).  The
    remaining text is kept verbatim, including ``^^hh`` escapes and ``/alt=``
    forms, because the MoonBit parser interprets them at runtime.
    """
    rel_path = "vendor/upstream/pyphen/hyph_%s.dic" % lang
    raw = read_bytes(rel_path)
    header, sep, remainder = raw.partition(b"\n")
    if not sep:
        raise GenError("%s: missing encoding header line" % rel_path)
    encoding = header.decode("ascii").strip()
    if encoding.lower() == "microsoft-cp1251":
        encoding = "cp1251"
    decoded = remainder.decode(encoding)
    lines: list[str] = []
    for line in decoded.split("\n"):
        line = line.strip()
        if not line or line.startswith(PYPHEN_IGNORED):
            continue
        lines.append(line)
    return {
        "path": rel_path,
        "encoding": encoding,
        "bytes": len(raw),
        "sha256": sha256_hex(raw),
        "lines": lines,
    }


def norm_patterns(hd) -> dict:
    """Normalize a parsed HyphDict for equality checks (keeps /alt= payloads)."""
    out = {}
    for key, (start, values) in hd.patterns.items():
        out[key] = (
            start,
            tuple((int(v), getattr(v, "data", None)) for v in values),
        )
    return out


def verify_patterns_roundtrip(lang: str, lines: list[str]) -> None:
    """Prove that re-encoding the decoded lines to UTF-8 is behavior-preserving."""
    source_path = REPO / ("vendor/upstream/pyphen/hyph_%s.dic" % lang)
    with tempfile.TemporaryDirectory(prefix="moon_textstat_l2_") as tmp:
        tmp_path = Path(tmp) / ("hyph_%s.dic" % lang)
        payload = "UTF-8\n" + "\n".join(lines) + "\n"
        tmp_path.write_bytes(payload.encode("utf-8"))
        original = pyphen.Pyphen(filename=str(source_path)).hd
        regenerated = pyphen.Pyphen(filename=str(tmp_path)).hd
    if norm_patterns(original) != norm_patterns(regenerated):
        raise GenError("%s: re-encoded lines change pyphen patterns" % lang)
    if original.maxlen != regenerated.maxlen:
        raise GenError("%s: re-encoded lines change pyphen maxlen" % lang)


def parse_cmudict() -> tuple[dict[str, list[str]], list[str]]:
    """Parse cmudict exactly like ``nltk.corpus.cmudict.dict()``.

    Per line ``WORD COUNTER PHONES...`` -- key is ``WORD.lower()``, value is the
    phone list starting at index 2, and a word's first pronunciation is the
    first line for that word in file order.
    """
    first: dict[str, list[str]] = {}
    order: list[str] = []
    with open(REPO / CMUDICT_REL, encoding="utf-8") as stream:
        for line in stream:
            pieces = line.split()
            if not pieces:
                continue
            word = pieces[0].lower()
            if word not in first:
                first[word] = pieces[2:]
                order.append(word)
    return first, order


def cmu_syllables(phones: list[str]) -> int:
    return sum(1 for phone in phones if phone[-1].isdigit())


def load_easy_words(root: str) -> list[str]:
    rel_path = "vendor/upstream/easy_words/%s/easy_words.txt" % root
    text = read_bytes(rel_path).decode("utf-8")
    words = set()
    for line in text.split("\n"):
        line = line.strip()
        if line:
            words.add(line)
    return sorted(words)


# --------------------------------------------------------------------------
# Oracle sample verification
# --------------------------------------------------------------------------


def list_words(text: str) -> list[str]:
    text = RE_NONCONTRACTION_APOSTROPHE.sub("", text)
    text = RE_NON_APOSTROPHE_PUNCTUATION.sub("", text)
    return text.lower().split()


def syllable_total(
    text: str,
    trimmed_map: dict[str, int],
    fallback,
    use_trimmed: bool,
) -> int:
    total = 0
    for word in list_words(text):
        count = trimmed_map.get(word) if use_trimmed else None
        if count is None:
            count = len(fallback.positions(word)) + 1
        total += count
    return total


def verify_samples(
    trimmed_map: dict[str, int],
    en_us,
    es,
) -> tuple[list, list, list[str]]:
    doc = json.loads(ORACLE_PATH.read_text(encoding="utf-8"))
    rows: list[tuple[str, int, int, bool]] = []
    es_rows: list[tuple[str, int, int, bool]] = []
    failures: list[str] = []
    for sample in doc["samples"]:
        # gen_oracle_smoke.py runs every sample's `results` group under en_US.
        computed = syllable_total(sample["text"], trimmed_map, en_us, True)
        expected = sample["results"]["syllable_count"]["value"]
        ok = computed == expected
        rows.append((sample["id"], computed, expected, ok))
        if not ok:
            failures.append(
                "oracle sample %s: computed %d, expected %d"
                % (sample["id"], computed, expected)
            )
        if sample["id"] == "spanish_text":
            # `results_es` was recorded under es_ES: no CMU table involved.
            computed_es = syllable_total(sample["text"], trimmed_map, es, False)
            expected_es = sample["results_es"]["syllable_count"]["value"]
            ok_es = computed_es == expected_es
            es_rows.append((sample["id"], computed_es, expected_es, ok_es))
            if not ok_es:
                failures.append(
                    "oracle sample %s (es_ES): computed %d, expected %d"
                    % (sample["id"], computed_es, expected_es)
                )
    return rows, es_rows, failures


# --------------------------------------------------------------------------
# In-memory model of all generated data
