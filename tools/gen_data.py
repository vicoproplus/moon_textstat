def print_report(data: GeneratedData) -> None:
    print("L1_CHECKED=%d L1_MISMATCH=%d" % (data.l1_checked, len(data.l1_failures)))
    for failure in data.l1_failures:
        print("L1_FAIL %s" % failure)
    pinned_bad = data.pronunciation_entries != PINNED_PRONUNCIATION_ENTRIES
    print(
        "PRONUNCIATION entries=%d pinned=%d %s"
        % (
            data.pronunciation_entries,
            PINNED_PRONUNCIATION_ENTRIES,
            "FAIL" if pinned_bad else "OK",
        )
    )
    supplement_bad = (
        data.pronunciation_supplement_entries
        != PINNED_PRONUNCIATION_SUPPLEMENT_ENTRIES
    )
    print(
        "PRONUNCIATION_SUPPLEMENT entries=%d pinned=%d %s rows_bytes=%d rows_sha256=%s"
        % (
            data.pronunciation_supplement_entries,
            PINNED_PRONUNCIATION_SUPPLEMENT_ENTRIES,
            "FAIL" if supplement_bad else "OK",
            data.pronunciation_supplement_rows_bytes,
            data.pronunciation_supplement_rows_sha256,
        )
    )
    print(
        "PRONUNCIATION_ROWS primary_bytes=%d primary_sha256=%s "
        "supplement_bytes=%d supplement_sha256=%s"
        % (
            data.pronunciation_rows_bytes,
            data.pronunciation_rows_sha256,
            data.pronunciation_supplement_rows_bytes,
            data.pronunciation_supplement_rows_sha256,
        )
    )
    for lang in PATTERN_LANGS:
        info = data.patterns.get(lang)
        if info is None:
            print("PATTERNS %-5s MISSING (build aborted)" % lang)
            continue
        pinned = info["pinned_lines"]
        if pinned is None:
            print(
                "PATTERNS %-5s lines=%d pinned=unpinned encoding=%s distinct=%d"
                % (lang, len(info["lines"]), info["encoding"], info["distinct_patterns"])
            )
        else:
            ok = len(info["lines"]) == pinned
            print(
                "PATTERNS %-5s lines=%d pinned=%d %s"
                % (lang, len(info["lines"]), pinned, "OK" if ok else "FAIL")
            )
    for root in EASY_ROOTS:
        count = len(data.easy_words.get(root, []))
        pinned = PINNED_EASY_ENTRIES[root]
        print(
            "EASY_WORDS %-2s entries=%d pinned=%d %s"
            % (root, count, pinned, "OK" if count == pinned else "FAIL")
        )
    for sample_id, computed, expected, ok in data.sample_rows:
        print(
            "SAMPLE %-28s computed=%-5d oracle=%-5d %s"
            % (sample_id, computed, expected, "OK" if ok else "MISMATCH")
        )
    print(
        "SAMPLES=%d MISMATCH=%d"
        % (len(data.sample_rows), sum(1 for row in data.sample_rows if not row[3]))
    )
    print(
        "SAMPLES_ES=%d MISMATCH_ES=%d"
        % (
            len(data.sample_es_rows),
            sum(1 for row in data.sample_es_rows if not row[3]),
        )
    )
    for code, computed, expected, ok in data.probe_rows:
        print(
            "PROBE %-5s computed=%-5d oracle=%-5d %s"
            % (code, computed, expected, "OK" if ok else "MISMATCH")
        )
    for code, error, asserted in data.probe_skips:
        print(
            "PROBE_SKIP %-5s oracle_error=%r %s"
            % (code, error, "ASSERTED" if asserted else "UNEXPECTED")
        )
    print(
        "PROBES=%d MISMATCH=%d"
        % (
            len(data.probe_rows),
            sum(1 for row in data.probe_rows if not row[3]),
        )
    )
    if data.l3 is not None:
        l3 = data.l3
        print("L3_CELLS=%d" % len(l3.cells))
        print("L3_SAMPLE=%d L3_LANG=%d" % (l3.sample_cells, l3.lang_cells))
        print(
            "L3_GROUPS %s"
            % " ".join(
                "%s=%d" % (group, l3.groups[group]) for group in L3_GROUP_ORDER
            )
        )
        print("L3_PT=%d" % l3.pt_cells)
        print("L3_EXT=%d" % l3.ext_cells)
        print(
            "L3_SHAPES align=%d ext=%d probe_fields=%d excluded_probe_fields=%d"
            % (
                len(l3.align_shapes),
                len(l3.ext_shapes),
                len(l3.probe_fields),
                len(l3.probe_excluded),
            )
        )
        print(
            "L3_ORACLE bytes=%d sha256=%s"
            % (l3.oracle_bytes, l3.oracle_sha256)
        )
    if data.zh is not None:
        zh = data.zh
        print(
            "ZH_TABLE bytes=%d entries=%d sha256=%s"
            % (zh.table_bytes, len(zh.chars), zh.table_sha256)
        )
        print(
            "ZH_INLINED payload_chars=%d chunks=%d sorted_rows_sha256=%s"
            % (
                zh.payload_chars,
                zh.chunks,
                zh.sorted_rows_sha256,
            )
        )
        print("ZH_CELLS=%d ZH_CASES=%d" % (len(zh.cells), len(ZH_CASES)))


def write_outputs(outputs: dict[str, tuple[str, dict]], manifest: str) -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    GATE_DATA_DIR.mkdir(parents=True, exist_ok=True)
    for rel_path in sorted(outputs):
        content, _ = outputs[rel_path]
        target = REPO / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode("utf-8"))
        print("WROTE %s" % rel_path)
    MANIFEST_PATH.write_bytes(manifest.encode("utf-8"))
    print("WROTE tools/l2_manifest.json")


def check_outputs(outputs: dict[str, tuple[str, dict]], manifest: str) -> list[str]:
    problems: list[str] = []
    ok = diff = missing = 0
    for rel_path in sorted(outputs):
        expected, _ = outputs[rel_path]
        target = REPO / rel_path
        if not target.exists():
            print("FILE %-44s MISSING" % rel_path)
            problems.append("missing %s" % rel_path)
            missing += 1
            continue
        if target.read_bytes() == expected.encode("utf-8"):
            print("FILE %-44s OK" % rel_path)
            ok += 1
        else:
            print("FILE %-44s DIFF" % rel_path)
            problems.append("diff %s" % rel_path)
            diff += 1
    print("FILES=%d OK=%d DIFF=%d MISSING=%d" % (len(outputs), ok, diff, missing))
    if not MANIFEST_PATH.exists():
        print("MANIFEST MISSING")
        problems.append("missing tools/l2_manifest.json")
    elif MANIFEST_PATH.read_bytes() == manifest.encode("utf-8"):
        print("MANIFEST OK")
    else:
        print("MANIFEST DIFF")
        problems.append("diff tools/l2_manifest.json")
    return problems


def run(args) -> int:
    data = build()
    if data.failures:
        print_report(data)
        for failure in data.failures:
            print("FAIL %s" % failure)
        print("CHECK=FAIL")
        return 1

    outputs = build_outputs(data)
    for rel_path in sorted(outputs):
        validate_source(outputs[rel_path][0], rel_path)
    manifest = make_manifest(data, outputs)

    print_report(data)

    if args.check:
        problems = check_outputs(outputs, manifest)
        if problems:
            print("CHECK=FAIL")
            return 1
        print("CHECK=PASS")
        return 0

    write_outputs(outputs, manifest)
    print("CHECK=PASS")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated files and data fidelity without writing",
    )
    args = parser.parse_args(argv)
    try:
        return run(args)
    except GenError as exc:
        print("GEN_ERROR %s" % exc)
        print("CHECK=FAIL")
        return 1
    except Exception as exc:  # no traceback on any emission/build failure
        print("GEN_ERROR %s: %s" % (type(exc).__name__, exc))
        print("CHECK=FAIL")
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
